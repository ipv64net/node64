package geoip

import "unicode/utf8"

// Flag liefert die Flagge eines Laendercodes als Emoji (zwei Regional Indicator Symbols, keine Bilder); "" fuer
// unbekannte Codes.
func Flag(cc string) string {
	if _, ok := countryNames[cc]; !ok {
		return ""
	}
	var b [8]byte
	n := utf8.EncodeRune(b[:], rune(0x1F1E6+int(cc[0]-'A')))
	n += utf8.EncodeRune(b[n:], rune(0x1F1E6+int(cc[1]-'A')))
	return string(b[:n])
}

// Name liefert den Laendernamen auf Deutsch (lang "de…") bzw. Englisch; unbekannt = der Code selbst.
func Name(cc, lang string) string {
	n, ok := countryNames[cc]
	if !ok {
		return cc
	}
	if len(lang) >= 2 && lang[:2] == "de" {
		return n[0]
	}
	return n[1]
}

